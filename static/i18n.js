/* 中英切换。
 *
 * 纯静态字典，没有后端参与——界面语言是每个浏览器自己的偏好，存 localStorage，
 * 不写进 config.json（那是服务端配置，换个浏览器看不应该被别人的偏好影响）。
 *
 * 两种用法：
 *   1. HTML 里标 data-i18n="key"，切换语言时由 applyStatic() 统一刷一遍
 *   2. JS 里动态拼的字符串用 t('key', {n: 3})
 *
 * 字典分段用 add() 累加，找起来方便，也不至于一个对象几百行。
 */
'use strict';

const I18N = { zh: {}, en: {} };
function add(zh, en) { Object.assign(I18N.zh, zh); Object.assign(I18N.en, en); }

const LANG_KEY = 'stockwatch.lang';

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch (e) { /* 隐私模式下 localStorage 会抛，忽略 */ }
  // 浏览器语言是 zh-* 就用中文，其余一律英文
  return /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
}

let LANG = detectLang();

const getLang = () => LANG;
/* 日期/数字用的 locale。数字分组符两边一致（都用千分位逗号），只有日期真的不同。 */
const dateLocale = () => (LANG === 'zh' ? 'zh-CN' : 'en-GB');   // en-GB = 日/月/年，欧洲人看着顺

/* 取一条文案。缺键时回落到中文，再不行就把 key 原样显示——
 * 显示 key 比显示空白好，漏翻译一眼就能看见。 */
function t(key, vars) {
  let s = I18N[LANG][key];
  if (s === undefined) s = I18N.zh[key];
  if (s === undefined) return key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(vars[k]);
  }
  return s;
}

/* 刷新一棵子树里所有带标记的节点。切换语言和渲染完动态内容后都要调。 */
function applyStatic(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  // 带 <b>/<br> 的整段说明文字。字典里的内容是我们自己写死的，不是用户输入，可以直接 innerHTML
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  if (root === document) {
    document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';
    const title = document.querySelector('title[data-i18n]');
    if (title) document.title = t(title.dataset.i18n);
  }
}

/* 切换语言。onChange 由各页面提供，用来重画动态内容（表格、卡片、图表）。 */
let onLangChange = null;
function setLang(lang) {
  if (lang !== 'zh' && lang !== 'en') return;
  LANG = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* 忽略 */ }
  applyStatic(document);
  syncToggle();
  if (onLangChange) onLangChange();
}

function syncToggle() {
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === LANG);
  });
}

/* 页面初始化时调一次：绑好切换按钮、刷一遍静态文案。 */
function initI18n(onChange) {
  onLangChange = onChange || null;
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
  applyStatic(document);
  syncToggle();
}

